// Seed: demo user + sample project with a pre-built dashboard document.
// Run: pnpm --filter @ai-mockup-studio/api db:seed   (after `db:migrate`/`db:push`)
import "dotenv/config";
import { eq } from "drizzle-orm";
import { db, pool } from "./index";
import { users, projects, documents, versions } from "./schema";
import { buildSampleDashboard } from "../sample-documents";

async function main() {
  const demoEmail = "demo@mockup.studio";

  let user = await db.select().from(users).where(eq(users.email, demoEmail)).limit(1);
  if (user.length === 0) {
    user = await db.insert(users).values({ email: demoEmail, name: "Demo User" }).returning();
  }
  const demo = user[0];

  const existing = await db.select().from(projects).where(eq(projects.ownerId, demo.id)).limit(1);
  if (existing.length > 0) {
    console.log("Seed: demo project đã tồn tại, bỏ qua.");
    return;
  }

  const doc = buildSampleDashboard("CRM Dashboard Demo");
  const [project] = await db.insert(projects).values({
    name: "CRM Dashboard Demo",
    description: "Sample project generated by seed",
    ownerId: demo.id,
  }).returning();

  const [document] = await db.insert(documents).values({
    projectId: project.id,
    schemaVersion: doc.schemaVersion,
    schema: doc as unknown as object,
  }).returning();

  await db.insert(versions).values({
    documentId: document.id,
    snapshot: doc as unknown as object,
    note: "Initial",
    createdBy: demo.id,
  });

  await db.update(projects)
    .set({ currentPageId: doc.pageId })
    .where(eq(projects.id, project.id));

  console.log(`Seed ok. Project id: ${project.id}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => pool.end());
